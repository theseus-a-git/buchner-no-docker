def test_velocity_update_matches_matlab_reference():
    """
    @brief Verify velocity update computation matches Matlab reference output.

    This regression test compares the Python implementation against
    reference data generated by the original Matlab implementation.
    """
    base_dir = Path(__file__).resolve().parent / "data/"
    N_x = 4
    config = build_config("inertia")
    
    # Load the reference data
    particle_init = list(np.loadtxt(base_dir / "Initialized_particles_matlab_1p_4x.txt"))
    particle_before = np.empty((2, N_x))
    for j in range(2):
        for x in range(N_x):
            particle_before[j, x] = particle_init.pop(0)
                
    particles = list(np.loadtxt(base_dir / "Iterated_particles_matlab_1p_4x.txt"))
    particle_after = np.empty((2, N_x))
    for j in range(2):
        for x in range(N_x):
            particle_after[j, x] = particles.pop(0)
            
    pbest = np.loadtxt(base_dir / "pbest_positions_matlab_1p_4x.txt")
    lbest = np.loadtxt(base_dir / "lbest_positions_matlab_1p_4x.txt")

    R1 = np.loadtxt(base_dir / "R1_vals_1p_4x.txt")
    R2 = np.loadtxt(base_dir / "R2_vals_1p_4x.txt")
    
    # calculate using python
    upd_vel_func = make_update_velocity(config)
    updated_velocity = upd_vel_func(0.9, 
                                    particle_before[0,:], 
                                    particle_before[1,:],
                                    R1,
                                    R2,
                                    pbest,
                                    lbest)
    
    # compare against matlab
    for x in range(N_x):
        assert updated_velocity[x] == particle_after[1, x]
    
        