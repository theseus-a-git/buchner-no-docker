"""
@file test_dynamical_equations.py
@brief Unit tests for PSO velocity update kernels.

This module contains unit tests for the velocity update kernels generated by
`make_update_velocity` in `dynamical_equations.py`.

The tests verify:

- Correct inertia-formulation velocity updates
- Correct constriction-formulation velocity updates
- Proper elementwise vector arithmetic
- Reduction to pure inertia when acceleration terms vanish
- Reduction to pure inertia when pbest and lbest equal the current position
- Independence of the constriction formulation from the inertia parameter
- Preservation of input arrays
- Output array shape and dtype consistency
- Proper handling of unsupported dynamical equation types

The tests are deterministic and designed for use with pytest.

@author
Ben Carlson

@date
2026-06-29
"""

import numpy as np
import pytest
from numpy.testing import assert_allclose
from pathlib import Path

from core.dynamical_equations import make_update_velocity


def build_config(eq_type="inertia", C1=2.0, C2=2.0):
    """
    @brief Construct a minimal PSO configuration object for testing.

    @param eq_type
        Dynamical equation type.

    @param C1
        Cognitive acceleration coefficient.

    @param C2
        Social acceleration coefficient.

    @return
        Lightweight configuration object.
    """

    class DummyConfig:
        pass

    cfg = DummyConfig()
    cfg.C1 = C1
    cfg.C2 = C2
    cfg.eq_type = eq_type

    return cfg


def test_inertia_velocity_update():
    """
    @brief Verify inertia-formulation velocity update.

    Confirms that the returned kernel produces the analytical
    inertia-update equation.
    """

    config = build_config("inertia")

    vel_fn = make_update_velocity(config)

    w = 0.5

    prev_x = np.array([1.0, 2.0, 3.0])
    prev_v = np.array([0.1, 0.2, 0.3])

    R1 = np.ones(3)
    R2 = np.ones(3)

    pbest = np.array([2.0, 3.0, 4.0])
    lbest = np.array([3.0, 4.0, 5.0])

    result = vel_fn(
        w,
        prev_x,
        prev_v,
        R1,
        R2,
        pbest,
        lbest
    )

    expected = (
        w * prev_v
        + 2.0 * (pbest - prev_x)
        + 2.0 * (lbest - prev_x)
    )

    assert_allclose(result, expected)


def test_constriction_velocity_update():
    """
    @brief Verify constriction-formulation velocity update.

    Confirms that the returned kernel produces the analytical
    constriction-update equation.
    """

    config = build_config("constriction")

    vel_fn = make_update_velocity(config)

    prev_x = np.array([1.0, 2.0])
    prev_v = np.array([0.1, 0.2])

    R1 = np.ones(2)
    R2 = np.ones(2)

    pbest = np.array([2.0, 3.0])
    lbest = np.array([3.0, 4.0])

    result = vel_fn(
        999.0,
        prev_x,
        prev_v,
        R1,
        R2,
        pbest,
        lbest
    )

    phi = 4.0

    K = 2.0 / abs(
        2.0 - phi - np.sqrt(phi * phi - 4.0 * phi)
    )

    expected = K * (
        prev_v
        + 2.0 * (pbest - prev_x)
        + 2.0 * (lbest - prev_x)
    )

    assert_allclose(result, expected)


def test_inertia_elementwise_behavior():
    """
    @brief Verify velocity updates are performed independently for each
    coordinate.
    """

    config = build_config("inertia")

    vel_fn = make_update_velocity(config)

    prev_x = np.array([10.0, -10.0])
    prev_v = np.array([1.0, 2.0])

    R1 = np.array([0.5, 2.0])
    R2 = np.array([1.0, 1.0])

    pbest = prev_x.copy()
