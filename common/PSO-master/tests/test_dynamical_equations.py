def test_inputs_are_not_modified():
    """
    @brief Verify velocity-update kernels do not modify input arrays.
    """

    config = build_config("inertia")

    vel_fn = make_update_velocity(config)

    prev_x = np.array([1.0, 2.0])
    prev_v = np.array([0.1, 0.2])

    R1 = np.array([0.3, 0.4])
    R2 = np.array([0.5, 0.6])

    pbest = np.array([2.0, 3.0])
    lbest = np.array([4.0, 5.0])

    originals = [
        arr.copy()
        for arr in (prev_x, prev_v, R1, R2, pbest, lbest)
    ]

    vel_fn(
        0.5,
        prev_x,
        prev_v,
        R1,
        R2,
        pbest,
        lbest
    )

    for original, current in zip(
        originals,
        (prev_x, prev_v, R1, R2, pbest, lbest)
    ):
        assert np.array_equal(original, current)


