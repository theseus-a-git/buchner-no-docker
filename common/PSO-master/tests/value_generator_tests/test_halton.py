def test_halton_streams_are_independent():
    """
    @brief Verify separate Halton generators maintain independent state.
    
    Creating multiple generators with the same configuration should
    create separate Halton engines. Advancing one generator must not
    affect the sequence produced by another generator.
    """
    config = MockPSOConfig(N_x=3)
    
    halton1 = make_halton(config, 0, 0)
    halton2 = make_halton(config, 0, 0)
    
    first_vals = halton1(10, 3)
    
    # Advance only halton1.
    halton1(10, 3)
    
    second_vals = halton2(10, 3)
    
    # halton2 should still produce the first sequence.
    np.testing.assert_array_equal(first_vals, second_vals)


def test_repeated_calls_continue_halton_sequence():
    """
    @brief Verify consecutive calls continue the same Halton sequence.
    
    Calling the returned callable multiple times should advance the
    underlying Halton engine rather than restarting the sequence.
    
    The combined output from two consecutive calls should therefore
    match the output from a single call requesting the same total
    number of points.
    """
    config = MockPSOConfig(N_x=3)
    
    halton1 = make_halton(config, 0, 0)
    halton2 = make_halton(config, 0, 0)
    
    first = halton1(10, 3)
    second = halton1(10, 3)
    
    expected = halton2(20, 3)
    
    np.testing.assert_array_equal(
        first,
        expected[:10],
    )
    np.testing.assert_array_equal(
        second,
        expected[10:],
    )


def test_first_points_are_reproducible_across_new_generators():
    """
    @brief Verify newly created generators begin at the same sequence point.
    
    Two separately created Halton generators using the same run-specific
    seed and generator index should begin at the same scrambled Halton
    sequence position.
    """
    config = MockPSOConfig(
        N_x=4,
        seed_vals=[
            np.array([9876, 9877], dtype=np.uint64),
            np.array([10000, 10001], dtype=np.uint64),
            np.array([20000, 20001], dtype=np.uint64),
        ],
    )
    
    halton1 = make_halton(config, 0, 0)
    halton2 = make_halton(config, 0, 0)
    
    first1 = halton1(1, 4)
    first2 = halton2(1, 4)
    
    np.testing.assert_array_equal(first1, first2)

