def test_zero_length_request():
    """
    @brief Verify requesting zero Halton points returns an empty array.
    
    A zero-length request should preserve the configured Halton
    dimensionality while returning no points.
    """
    config = MockPSOConfig(N_x=5)
    
    halton = make_halton(config, 0, 0)
    
    vals = halton(0, 5)
    
    assert vals.shape == (0, 5)
    assert vals.size == 0


def test_arbitrary_batch_size():
    """
    @brief Verify Halton generation supports arbitrary batch sizes.
    
    Unlike sequence generators that require power-of-two batch sizes,
    the Halton implementation uses SciPy's `random()` method and
    therefore supports an arbitrary number of requested points.
    
    This test uses a batch size that is not a power of two.
    """
    config = MockPSOConfig(N_x=4)
    
    halton = make_halton(config, 0, 0)
    
    vals = halton(7, 4)
    
    assert vals.shape == (7, 4)
    assert vals.size == 28
    assert np.all(vals >= 0.0)
    assert np.all(vals < 1.0)


def test_m_dimension_matches_configured_dimension():
    """
    @brief Verify the configured N_x dimension controls the Halton engine.
    
    The M argument is part of the common value-generator interface, but
    the Halton implementation obtains its actual dimensionality from
    `config.N_x`.
    
    This test verifies that the generated points use the configured
    dimensionality rather than the M argument.
    """
    config = MockPSOConfig(N_x=6)
    
    halton = make_halton(config, 0, 0)
    
    vals = halton(8, 2)
    
    assert vals.shape == (8, 6)
