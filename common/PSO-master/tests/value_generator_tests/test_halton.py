def test_seed_reproducibility():
    """
    @brief Verify identical seeds produce identical Halton sequences.
    
    Two Halton generators initialized with the same run-specific seed,
    generator index, and dimension should produce identical scrambled
    Halton points.
    """
    config = MockPSOConfig(
        N_x=5,
        seed_vals=[
            np.array([42, 43], dtype=np.uint64),
            np.array([100, 101], dtype=np.uint64),
            np.array([200, 201], dtype=np.uint64),
        ],
    )
    
    halton1 = make_halton(config, 0, 0)
    halton2 = make_halton(config, 0, 0)
    
    vals1 = halton1(20, 5)
    vals2 = halton2(20, 5)
    
    np.testing.assert_array_equal(vals1, vals2)


def test_seed_independence():
    """
    @brief Verify different seeds produce different Halton sequences.
    
    Different scrambling seeds should produce different Halton
    sequences while retaining the same dimensionality.
    """
    config1 = MockPSOConfig(
        N_x=5,
        seed_vals=[
            np.array([1, 3], dtype=np.uint64),
            np.array([10, 30], dtype=np.uint64),
            np.array([100, 300], dtype=np.uint64),
        ],
    )
    config2 = MockPSOConfig(
        N_x=5,
        seed_vals=[
            np.array([2, 4], dtype=np.uint64),
            np.array([20, 40], dtype=np.uint64),
            np.array([200, 400], dtype=np.uint64),
        ],
    )
    
    halton1 = make_halton(config1, 0, 0)
    halton2 = make_halton(config2, 0, 0)
    
    vals1 = halton1(20, 5)
    vals2 = halton2(20, 5)
    
    assert not np.array_equal(vals1, vals2)


def test_seed_sequence_reproducibility():
    """
    @brief Verify SeedSequence objects provide reproducible Halton streams.
    
    Two equivalent NumPy SeedSequence objects should result in identical
    NumPy Generators and therefore identical scrambled Halton sequences.
    """
    seed1 = np.random.SeedSequence(12345)
    seed2 = np.random.SeedSequence(12345)
    
    config1 = MockPSOConfig(
        N_x=5,
        seed_vals=[
            np.array([seed1, np.random.SeedSequence(1)], dtype=object),
            np.array(
                [np.random.SeedSequence(2), np.random.SeedSequence(3)],
                dtype=object,
            ),
            np.array(
                [np.random.SeedSequence(4), np.random.SeedSequence(5)],
                dtype=object,
            ),
        ],
    )
    
    config2 = MockPSOConfig(
        N_x=5,
        seed_vals=[
            np.array([seed2, np.random.SeedSequence(1)], dtype=object),
            np.array(
                [np.random.SeedSequence(2), np.random.SeedSequence(3)],
                dtype=object,
            ),
            np.array(
                [np.random.SeedSequence(4), np.random.SeedSequence(5)],
                dtype=object,
            ),
        ],
    )
    
    halton1 = make_halton(config1, 0, 0)
    halton2 = make_halton(config2, 0, 0)
    
    np.testing.assert_array_equal(
        halton1(20, 5),
        halton2(20, 5),
    )


