"""
@file test_halton.py

@brief Unit tests for Halton quasirandom-value generation.

This module contains unit tests for the `make_halton` factory function
defined in:

@code
PSO.options.value_generators.halton
@endcode

The tests verify:

* Correct generation of Halton values with requested dimensions
* Values are within the interval [0, 1)
* Reproducibility using integer seeds
* Independence of Halton streams using different seeds
* Independent state between separately created generators
* Zero-length requests
* Generation across multiple dimensions
* Reproducibility using SeedSequence objects
* Correct selection of the run-specific seed
* Correct selection of the generator-specific seed
* Continuation of the Halton sequence across multiple calls
* Support for arbitrary batch sizes
* Use of the configured search-space dimensionality

These tests are designed for use with pytest.

@author
Ben Carlson

@date
2026-09-09
"""
from dataclasses import dataclass, field
import numpy as np

from options.value_generators.halton import make_halton

# ============================================================================
# Test configuration
# ============================================================================

N_RUNS = 2
N_GENERATORS = 3

@dataclass
class MockPSOConfig:
    """
    @brief Lightweight configuration object for testing.
    
    This class provides only the configuration members required by
    `make_halton`.
    
    @param N_x
    Number of dimensions in the Halton sequence.
    
    @param seed_vals
    Three-element sequence containing the seeds associated with the
    position, velocity, and update generators. Each generator contains
    one seed for each PSO run.
    """
    N_x: int = 2
    seed_vals: list = field(
        default_factory=lambda: [
            np.array([123, 456], dtype=np.uint64),
            np.array([789, 101112], dtype=np.uint64),
            np.array([131415, 161718], dtype=np.uint64),
        ]
    )

