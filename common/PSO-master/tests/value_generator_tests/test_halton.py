def test_halton_generation_shape():
    """
    @brief Verify generated Halton array has the requested shape.
    
    The returned callable should generate N rows and M columns, as
    specified by the PSO value-generator interface.
    """
    config = MockPSOConfig(N_x=3)
    
    halton = make_halton(config, 0, 0)
    
    vals = halton(10, 3)
    
    assert vals.shape == (10, 3)


def test_halton_generation_range():
    """
    @brief Verify generated Halton values lie in the interval [0, 1).
    
    Halton points generated by SciPy should contain floating-point
    values greater than or equal to zero and strictly less than one.
    """
    config = MockPSOConfig(N_x=5)
    
    halton = make_halton(config, 0, 0)
    
    vals = halton(100, 5)
    
    assert np.all(vals >= 0.0)
    assert np.all(vals < 1.0)
    
    
def test_halton_generation_multiple_dimensions():
    """
    @brief Verify Halton values are generated across multiple dimensions.
    
    This test verifies that the Halton engine is initialized with the
    configured number of dimensions and produces the expected number
    of values.
    """
    config = MockPSOConfig(N_x=7)
    
    halton = make_halton(config, 0, 0)
    
    vals = halton(4, 7)
    
    assert vals.shape == (4, 7)
    assert vals.size == 28
    assert np.all(vals >= 0.0)
    assert np.all(vals < 1.0)

